'use strict';
// This file provides some functions for downloading and updating the client error config

const fs = require('fs');
const {fetchJSON} = require('./network');
const { NoStackError } = require('./utilities');

const localClientErrorConfigUrl = 'https://d0.tubitv.com/error-handler/client-error-config.json';

const localClientErrorConfigFilePath = 'src/channel/source/localClientErrorConfig.brs';


async function generateLocalClientErrorConfigFileContents() {
  const localClientErrorConfig = await fetchJSON(localClientErrorConfigUrl);

  const fileContents = `
' This file is automatically generated by the gulp task generateLocalClientErrorConfigFileContents and should not be manually updated
Function getLocalClientErrorConfig()
  return ${JSON.stringify(localClientErrorConfig, null, 2)}
End Function`;
  return fileContents;
}


async function updateLocalClientErrorConfigFile(done) {
  const fileContents = await generateLocalClientErrorConfigFileContents();
  fs.writeFileSync(localClientErrorConfigFilePath, fileContents);
  done();
}


// Verify that the client error config file is up to date and current
async function verifyLocalClientErrorConfigIsCurrent(done) {
  const generatedLocalClientErrorConfig = await generateLocalClientErrorConfigFileContents();

  // Read the local file and compare to the generated file
  const existingLocalClientErrorConfig = fs.readFileSync(localClientErrorConfigFilePath, 'utf8');

  if (generatedLocalClientErrorConfig !== existingLocalClientErrorConfig) {
    done(new NoStackError(`The client error config file is out of date. Run the gulp task updateErrorConfig to update it.`));
  } else {
    done();
  }
}


module.exports = {
  generateLocalClientErrorConfigFileContents,
  updateLocalClientErrorConfigFile,
  verifyLocalClientErrorConfigIsCurrent
};
